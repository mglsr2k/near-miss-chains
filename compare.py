"""Answer the README's sample queries twice: the same model with no tools and no system prompt, and
the full agent. Writes both side by side to docs/sample_answers.md, for the README.

    uv run compare.py            # needs the same gcloud credentials as the app
"""

import asyncio
import json
from pathlib import Path

import litellm

import app
from context_panel import AgentContexts

SAMPLES = [
    "In near misses involving fatigue at night, what caught the error, and do fatigue accidents at night lack those defenses?",
    "What chains of factors lead to fuel-related near misses, and do the same chains appear in general aviation fuel accidents?",
    "How do runway incursions at airline (Part 121) operations usually get stopped, and what chain of factors precedes them?",
]


async def no_tools(question: str) -> str:
    r = await litellm.acompletion(model=app.MODEL.model, messages=[{"role": "user", "content": question}],
                                  vertex_location=app.SETTINGS.extra_args["vertex_location"], timeout=120)
    return r.choices[0].message.content


async def agent(question: str) -> dict:
    hooks = app.LeadTurns(AgentContexts(), lambda e: None)
    result = await app.deep_research(question, [], hooks)
    return app._payload(result, "compare", "compare")


async def main():
    out = ["# Sample queries: no tools vs. the agent\n",
           f"Model: `{app.MODEL.model}`. Generated by `uv run compare.py`.\n"]
    for i, q in enumerate(SAMPLES, 1):
        base, res = await asyncio.gather(no_tools(q), agent(q))
        calls = res.get("tool_calls", [])
        out += [f"## {i}. {q}\n", "### Same model, no tools, no system prompt\n", base.strip(), "\n",
                "### The agent\n", res["response"].strip(), "\n",
                f"*{res.get('researchers')} researchers, {res.get('rounds')} rounds, {len(calls)} tool calls, "
                f"{res.get('seconds')}s. Citations: {json.dumps(res.get('citations'))}*\n",
                "<details><summary>Tool calls</summary>\n\n```json\n" +
                json.dumps([{k: c[k] for k in ("agent", "name", "args")} for c in calls], indent=1) +
                "\n```\n</details>\n"]
        print(f"done {i}/{len(SAMPLES)}")
    Path("docs").mkdir(exist_ok=True)
    Path("docs/sample_answers.md").write_text("\n".join(out))
    print("wrote docs/sample_answers.md")


if __name__ == "__main__":
    asyncio.run(main())
